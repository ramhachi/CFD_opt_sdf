#!/usr/bin/env python3
"""SCREEN-01 (#64, M3b-1) builder: the G1 states through the harness state model, their direction raws, and the WaterLily harness campaigns (registration §3-§4;
interface of the analyzer: scripts/screen01/INTERFACE.md).  Solver-free and deterministic; every written file is regenerated byte for byte by --check.

    python scripts/screen01/screen01_build.py states [--check]                        # states.json + inputs/*.raw (every state must reproduce its P0 gated bytes)
    python scripts/screen01/screen01_build.py campaign g1 [--check]                   # docs/harness/screen01_campaign.json (g1k11, g1k12)
    python scripts/screen01/screen01_build.py campaign g2 --rs rs.json [--check]      # proposal states (states_g2.json, inputs/) + docs/harness/screen01_g2_campaign.json
    python scripts/screen01/screen01_build.py campaign f --finalist finalist.json [--check]   # docs/harness/screen01_f_campaign.json, screen01_f48_campaign.json

Smokes (scripts/harness.py smoke CAMPAIGN --source-commit X --kernel K): screen01 -> g1k11 (its first run is the parent at phase 11); screen01_g2 -> g2 (parent, phase 11);
screen01_f -> f32smk and screen01_f48 -> f48smk (smoke-only kernels: the parent alone at phase 20, no confirmation phase is touched; never pushed as formal kernels).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "scripts"), str(ROOT / "scripts/fid01"), str(ROOT / "scripts/screen01")]
import fid01_build as FB  # noqa: E402
import fid01_designs as D  # noqa: E402
import screen01_pool as P  # noqa: E402
import step01_states as S  # noqa: E402
import unc01_build as B  # noqa: E402

P0 = P.OUT
EV = P0.parent
STATES, STATES_G2 = EV / "states.json", EV / "states_g2.json"
HARNESS = ROOT / "docs/harness"
PARENT, REPEAT, ROLL = "v18__parent", "v18__parent__repeat", "v18__roll_p25"
RANK = ("parent", "axial", "design", "manual", "ref", "nc", "random")   # G1 run order (§4.2); the parent repeat is appended by the kernel

# registration §4.1 / §4.2: phases; caps = (per-state, aggregate, kernel timeout) in s; estimates come from fid01_build (415 / 2,340 s per run + 260 s per kernel)
EXPLORATION, F32_PHASES, F48_PHASES, REPLAY, SMOKE_PHASE = (11, 12), ((13, 14), (15, 16)), (13, 14), 11, 20
CAPS = {"g1": (900, 20000, 23300), "g2": (900, 6000, 9000), "f48": (6000, 9200, 12500), "f32a": (900, 7000, 10000), "f32b": (900, 6000, 9000)}
SMOKE_CAPS = {"flow_32": (900, 900, 4200), "flow_48": (6000, 6000, 9300)}   # not registered numbers: the cap of a formal run of one state plus setup (validate_kernel)
FORMAL = ("g1k11", "g1k12", "g2", "f48k13", "f48k14", "f32a", "f32b")


def dir_rel(name: str) -> str:
    return B.dir_rel(name) if name == ROLL else f"docs/evidence/screen01_2026_10_30/inputs/{name}.dir_f4_fortran.raw"


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)


def jtext(obj) -> str:
    return json.dumps(obj, indent=1, sort_keys=True) + "\n"


# ---- states ----------------------------------------------------------------------------------------------------------------------------------------
def build_state(s, p, parent_raw, name: str, spec: dict, gated_sha: str):
    """(direction raw bytes, harness state row) of one candidate; refuses unless the harness bytes equal the gated bytes and the runner regeneration reproduces them."""
    import v18_plate as V
    from cfd_sdf.fd08_v2_campaign import construct_state, state_identity
    dvec, step = V.harness_direction(s, D.design_phi(s, p, spec))
    child, audit = construct_state(s, dvec, step, 1)
    ident = state_identity(child)
    if ident["phi_fortran_order_sha256"] != gated_sha:
        raise SystemExit(f"{name}: harness bytes differ from the gated bytes")
    raw = S.to_raw(dvec)
    regen = S.perturb(parent_raw, np.frombuffer(raw, "<f4").reshape(S.SHAPE, order="F"), step, 1)
    if S.sha256_bytes(S.to_raw(regen)) != gated_sha:
        raise SystemExit(f"{name}: runner regeneration differs")
    return raw, {"kind": "candidate", "direction": name, "direction_path": dir_rel(name), "step_mm": float(step), "sign": 1, "direction_sha256_fortran_raw": S.sha256_bytes(raw),
                 "state_sha256": ident["state_sha256"], "npz_sha256": B.npz_sha(child), "phi_fortran_order_sha256": ident["phi_fortran_order_sha256"],
                 "phi_c_order_sha256": ident["phi_c_order_sha256"], "zero_level_margin_m": float(audit["zero_level_margin_m"]), "margin_tolerance_m": 1e-6,
                 "changed_node_count": int(audit["changed_node_count"]), "maximum_pointwise_change_m": float(audit["maximum_pointwise_change_m"])}


def p0_record():
    pools = json.loads((P0 / "pools.json").read_text())["pools"]
    rows = {r["name"]: r for r in map(json.loads, (P0 / "rows.jsonl").read_text().splitlines())}
    return pools, rows, json.loads((P0 / "summary.json").read_text())["pools"], json.loads((P0 / "design_check.json").read_text())


def g1_plan() -> list:
    """(name, role, order) of the P0-built G1 states: the 6 axial (mode order, + before -), the 9 design points (freeze order), M, ref, the 19 control states (sequence order)."""
    pools, rows, summ, dc = p0_record()
    m = summ["manual"][f"M_for_m_D_{P.M_D:g}"]
    if m is None:
        raise SystemExit("MANUAL_NONE: the P0 record has no admissible hand design (registration §3.3)")
    groups = {"axial": [D.name(x) for x in pools["axial"]], "design": dc["design_points"], "manual": [m], "ref": [D.name(x) for x in pools["ref"]],
              "random": summ["rand3"]["control_set"]}
    if [len(groups[k]) for k in ("axial", "design", "random")] != [6, 9, P.K_RAND]:
        raise SystemExit("the P0 record does not hold 6 axial, 9 design and 19 control states")
    return [(n, role, i) for role, names in groups.items() for i, n in enumerate(names)]


def candidate_rows(items: list, role_of: dict, s, p, parent_raw) -> tuple:
    """items = [(name, spec, gated phi SHA)] -> (rows, {raw path: bytes}); role_of[name] = (role, order)."""
    rows, files = {}, {}
    for name, spec, gated in items:
        raw, row = build_state(s, p, parent_raw, name, spec, gated)
        role, order = role_of[name]
        rows[name] = {**row, "role": role, "order": order, "u": P.spec_to_u(spec), "spec": spec}
        files[ROOT / row["direction_path"]] = raw
    return rows, files


def states_files() -> dict:
    import mode01_v18_prescreen as P18
    s, p = P18.load_parent()
    unc = json.loads(B.OUT.joinpath("states.json").read_text())
    p0rows = p0_record()[1]
    plan = g1_plan()
    items = []
    for name, role, _ in plan:
        r = p0rows[name]
        if not r["admissible"] or D.name(r["spec"]) != name:
            raise SystemExit(f"{name}: not an admissible P0 member (or its name is not the sorted-key name of its spec)")
        items.append((name, r["spec"], r["phi_fortran_sha256"]))
    rows, files = candidate_rows(items, {n: (role, i) for n, role, i in plan}, s, p, S.read_f4(ROOT / B.PARENT_RAW))
    base = {"u": None, "spec": None, "order": 0}
    rows[PARENT] = {**unc["states"][PARENT], "direction_path": None, "role": "parent", **base}
    rows[REPEAT] = {**rows[PARENT], "role": "parent_repeat", "kind": "parent_repeat"}
    rows[ROLL] = {**unc["states"][ROLL], "direction_path": B.dir_rel(ROLL), "role": "nc", **base}
    rec = {"schema": "screen01-states-v1", "parent": PARENT, "parent_record": unc["parent"], "v18_plate_sha256": FB.sha(ROOT / "scripts/v18_plate.py"),
           "unc01_states_sha256": FB.sha(B.OUT / "states.json"), "p0_sha256": {f: FB.sha(P0 / f) for f in ("pools.json", "rows.jsonl", "summary.json", "design_check.json")},
           "states": rows, "check": "every candidate's Fortran phi SHA equals its P0 gated bytes (rows.jsonl) and step01_states.perturb on the written raw reproduces it; "
                                    "parent and roll = UNC-01 rows; parent_repeat = the parent's bytes under its own name"}
    return {STATES: jtext(rec), **files}


def proposal_states(rs: dict) -> tuple:
    """(rows, {raw path: bytes}) of the proposal states of a written rs.json.  Fields used: proposals[].{name, u}, gating[].{name, admissible, phi_fortran_sha256}."""
    import mode01_v18_prescreen as P18
    props = rs["proposals"]
    if len(props) > P.N_PROP:
        raise SystemExit(f"{len(props)} proposals (registration: at most {P.N_PROP})")
    if not props:
        return {}, {}
    s, p = P18.load_parent()
    known, gating, items, order = set(json.loads(STATES.read_text())["states"]), {g["name"]: g for g in rs["gating"]}, [], {}
    for i, pr in enumerate(props):
        spec = dict(sorted(P.u_to_spec(pr["u"]).items()))
        name = D.name(spec)
        g = gating.get(name)
        if pr["name"] != name or name in known or name in order or not (g and g["admissible"] and g.get("phi_fortran_sha256")):
            raise SystemExit(f"proposal {pr['name']!r}: not a new admissible gated state named by its sorted-key spec ({name})")
        items.append((name, spec, g["phi_fortran_sha256"]))
        order[name] = ("proposal", i)
    return candidate_rows(items, order, s, p, S.read_f4(ROOT / B.PARENT_RAW))


# ---- campaigns ----------------------------------------------------------------------------------------------------------------------------------
def by_role(rows: dict, role: str) -> list:
    return [n for n, r in sorted(rows.items(), key=lambda kv: kv[1]["order"]) if r["role"] == role]


def load_rows() -> dict:
    rows = json.loads(STATES.read_text())["states"]
    return {**rows, **(json.loads(STATES_G2.read_text())["states"] if STATES_G2.exists() else {})}


def g1_kernels(rows: dict) -> dict:
    """g1k11 (39 runs, the repeat last) and g1k12 (38); the parent first, one phase per kernel (§4.2)."""
    order = [n for role in RANK for n in by_role(rows, role)]
    return {f"g1k{k}": B.kernel("screen01", f"g1k{k}", "flow_32", B.phase_runs(order, "flow_32", (k,)) + ([B.run(REPEAT, "flow_32", k)] if k == EXPLORATION[0] else []), *CAPS["g1"])
            for k in EXPLORATION}


def g2_kernels(proposals: list) -> dict:
    return {"g2": B.kernel("screen01_g2", "g2", "flow_32", B.phase_runs([PARENT, *proposals], "flow_32", EXPLORATION), *CAPS["g2"])}


def smoke_kernel(cid: str, case: str) -> dict:
    return B.kernel(cid, "f32smk" if case == "flow_32" else "f48smk", case, [B.run(PARENT, case, SMOKE_PHASE)], *SMOKE_CAPS[case])


def f_kernels(rows: dict, finalist: str, r_best: str | None) -> dict:
    """{"screen01_f": f32a, f32b, f32smk; "screen01_f48": f48k13, f48k14, f48smk}; an empty R-best drops its runs."""
    if rows.get(finalist, {}).get("role") not in ("axial", "design", "proposal") or (r_best and rows.get(r_best, {}).get("role") != "random"):
        raise SystemExit(f"finalist {finalist!r} / R-best {r_best!r} are not registered candidate / control states")
    cand = [PARENT, finalist, *([r_best] if r_best else [])]
    ctrl = cand + by_role(rows, "manual") + by_role(rows, "nc")
    f48 = {f"f48k{k}": B.kernel("screen01_f48", f"f48k{k}", "flow_48", B.phase_runs(cand, "flow_48", (k,)), *CAPS["f48"]) for k in F48_PHASES}
    f32 = {"f32a": B.kernel("screen01_f", "f32a", "flow_32", B.phase_runs(ctrl, "flow_32", F32_PHASES[0]) + [B.run(PARENT, "flow_32", REPLAY), B.run(REPEAT, "flow_32", F32_PHASES[0][0])],
                            *CAPS["f32a"]),
           "f32b": B.kernel("screen01_f", "f32b", "flow_32", B.phase_runs(ctrl, "flow_32", F32_PHASES[1]), *CAPS["f32b"])}
    return {"screen01_f": {**f32, "f32smk": smoke_kernel("screen01_f", "flow_32")}, "screen01_f48": {**f48, "f48smk": smoke_kernel("screen01_f48", "flow_48")}}


def campaign_text(cid: str, kernels: dict, rows: dict) -> tuple:
    from cfd_harness import campaign_schema as SC
    rec = json.loads(STATES.read_text())
    c = B.campaign(cid, kernels, {"parent": rec["parent_record"], "states": rows})
    c["directions"] = {n: {"path": rows[n]["direction_path"], "sha256_fortran_raw": rows[n]["direction_sha256_fortran_raw"]} for n in c["states"] if rows[n]["direction"]}
    SC.validate_campaign(c)
    return HARNESS / f"{cid}_campaign.json", jtext(c)


def campaign_files(which: str, rs_path: Path | None = None, finalist_path: Path | None = None) -> dict:
    rows = load_rows()
    if which == "g1":
        return dict([campaign_text("screen01", g1_kernels(rows), rows)])
    if which == "g2":
        rs = json.loads(Path(rs_path).read_text())
        new, files = proposal_states(rs)
        if not new:
            return {}
        rec = {"schema": "screen01-states-v1", "parent": PARENT, "rs_json_sha256": FB.sha(rs_path), "states": new}
        return {STATES_G2: jtext(rec), **files, **dict([campaign_text("screen01_g2", g2_kernels(list(new)), {**rows, **new})])}
    fin = json.loads(Path(finalist_path).read_text())
    if not fin.get("finalist"):
        raise SystemExit("no finalist: F is not pushed (registration §5.4)")
    return dict(campaign_text(cid, ks, rows) for cid, ks in f_kernels(rows, fin["finalist"], fin.get("r_best")).items())


def emit(files: dict, check: bool) -> None:
    """Write (refusing to overwrite a different file) or byte-check every file; text files are str, raws bytes."""
    data = {p: (b.encode() if isinstance(b, str) else b) for p, b in files.items()}
    bad = [rel(p) for p, b in data.items() if (p.exists() and p.read_bytes() != b) or (check and not p.exists())]
    if bad:
        raise SystemExit(("byte check FAILED: " if check else "refusing to overwrite different files: ") + ", ".join(bad))
    if check:
        return
    for p, b in data.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(b)


def summary(files: dict) -> dict:
    out = {}
    for p, text in files.items():
        if p.parent == HARNESS:
            for k, kern in json.loads(text)["kernels"].items():
                cfg = kern["config"]
                out[f"{p.stem[:-len('_campaign')]}/{k}"] = {"runs": len(kern["runs"]), "estimate_s": FB.estimate_s(kern),
                                                              "caps": [cfg["per_state_timeout_s"], cfg["solver_wall_time_cap_s"], cfg["kernel_timeout_s"]]}
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["states", "campaign"])
    ap.add_argument("which", nargs="?", choices=["g1", "g2", "f"])
    ap.add_argument("--rs", type=Path, default=EV / "rs.json")
    ap.add_argument("--finalist", type=Path, default=EV / "finalist.json")
    ap.add_argument("--check", action="store_true", help="regenerate and compare byte for byte; write nothing")
    a = ap.parse_args()
    if a.cmd == "campaign" and not a.which:
        ap.error("campaign needs g1, g2 or f")
    files = states_files() if a.cmd == "states" else campaign_files(a.which, a.rs, a.finalist)
    emit(files, a.check)
    print("byte check passed" if a.check else "written", len(files), "files")
    if a.cmd == "campaign":
        print(json.dumps(summary(files), indent=1))


if __name__ == "__main__":
    main()
